"""CustomSlop FastDL publisher for agitationskeleton/redchanitfastdl_tf2classic (GitHub Pages,
path prefix tf2classified/), modelled on tf2cc's tools/tf2c/fastdl_publish_tf2c.py (no clone:
Git Data API blobs -> trees (chunked, base_tree) -> one commit -> ref update).

Rules (HARD_RULES.txt + user decisions 2026-11-16):
  * only paths under CustomSlop-owned prefixes are ever added or deleted:
      tf2classified/models/customslop/  tf2classified/materials/models/customslop/
      tf2classified/materials/backpack/customslop/
    anything else in the plan is refused before any API call that writes
  * add-only for new paths; a path that already exists is left alone unless the catalogue says
    CustomSlop published exactly that blob (then it is identical and skipped)
  * delete only catalogue-recorded paths of retired weapons, and only if the blob currently in the
    repo is the one CustomSlop published (sha match); otherwise it is reported and left alone
  * the shared files scripts/items/custom_items_game.txt(.bz2) and custom_level_sounds.txt are
    NOT CustomSlop-owned (tf2cc publishes them): touched only with config allow_schema_replace=true
    AND a byte proof that the new file equals the published one plus/minus CustomSlop's own blocks
  * dry run by default; --apply writes ONE commit; the previous head is kept as the revert sha
    (--revert <sha> --apply works only while that commit is still the branch head)
  * after a write: poll the Pages build for the new commit; if it has not started/finished after
    STALL_MIN minutes, POST pages/builds once (it stalled once before) and keep polling; then HEAD
    every new URL until 200; the schema path is served with max-age=600, so callers wait 10 min
Every step is journaled in the catalogue; tokens come from the gh CLI's own store, never a file here.

  python -I publish.py                 (dry run: plan + remote existence check, GET only)
  python -I publish.py --offline       (plan only, no network)
  python -I publish.py --apply         (NOT used in research)
  python -I publish.py --revert <sha> --apply
"""
import argparse
import base64
import bz2
import datetime as dt
import hashlib
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.append(HERE)
import slopqueue as Q  # noqa: E402

OWN = ("tf2classified/models/customslop/", "tf2classified/materials/models/customslop/",
       "tf2classified/materials/backpack/customslop/")
SHARED = ("tf2classified/scripts/items/custom_items_game.txt.bz2", "tf2classified/scripts/items/custom_level_sounds.txt.bz2")
STALL_MIN = 12
LOG = os.path.join(Q.STATE_DIR, "publish_log.tsv")


def shared_files(repo, head, st, c):
    """The served schema + sound scripts (NOT CustomSlop-owned): only with allow_schema_replace.
    New content = the CURRENTLY PUBLISHED file with CustomSlop's own blocks cut out and the
    union of live + tonight's CustomSlop weapons inserted (apply.merge / merge_sounds keep the rest
    byte for byte and prove it). Returns blob dicts, or None when not allowed."""
    if not c.get("allow_schema_replace"):
        return None
    import apply as A
    live = [w for w in st["weapons"].values() if w["status"] in ("approved", "live")]
    cur = tree_lookup(repo, head, list(SHARED))
    out = []
    for path in SHARED:
        if not cur.get(path):
            raise SystemExit("shared file missing on FastDL: %s" % path)
        old_bz = base64.b64decode(gh("GET", "repos/%s/git/blobs/%s" % (repo, cur[path]))["content"])
        old = bz2.decompress(old_bz)
        new = A.merge(old, sorted(live, key=lambda w: w["defindex"]), st, c) if path.endswith("custom_items_game.txt.bz2") \
            else A.merge_sounds(old, live)
        data = bz2.compress(new, 9)
        out.append(dict(defindex=None, path=path, data=data, sha=git_sha(data), old_raw=len(old), new_raw=len(new),
                        old_bz2=len(old_bz)))
    return out


def commit_message(n_add, n_del):
    return ("CustomSlop: %d new file(s), %d retired file(s) removed (CustomSlop-owned paths only)\n\n"
            "Paths: %s\nGenerated by tf2c-customslop tools/publish.py. No other file is touched."
            % (n_add, n_del, ", ".join(OWN)))


def gh(method, path, body=None, check=True):
    cmd = ["gh", "api", "-X", method, path]
    if body is not None:
        cmd += ["--input", "-"]
    r = subprocess.run(cmd, input=json.dumps(body).encode() if body is not None else None, capture_output=True)
    if r.returncode != 0:
        if not check:
            return None
        raise SystemExit("gh api %s %s failed: %s" % (method, path, r.stderr.decode()[:300]))
    return json.loads(r.stdout or b"{}")


def git_sha(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def plan(st, c):
    adds, dels = [], []
    for w in st["weapons"].values():
        d = os.path.join(ROOT, w["dir"], "files")
        if w["status"] in ("approved", "live") and not w.get("published"):
            for rel in w["assets"]:
                adds.append(dict(defindex=w["defindex"], path=c["fastdl_prefix"] + rel + ".bz2", src=os.path.join(d, rel)))
        if w["status"] == "retired" and w.get("published") and not w.get("unpublished"):
            for rec in w.get("published_blobs", []):
                dels.append(dict(defindex=w["defindex"], path=rec["path"], sha=rec["sha"]))
    bad = [x["path"] for x in adds + dels if not x["path"].startswith(OWN)]
    if bad:
        raise SystemExit("refused: plan touches non-CustomSlop paths: %s" % bad[:10])
    return adds, dels


def tree_lookup(repo, head, paths):
    """Existing blob sha for each path (GET only, walks just the needed subtrees)."""
    cache = {}

    def listing(tree_sha):
        if tree_sha not in cache:
            cache[tree_sha] = {e["path"]: e for e in gh("GET", "repos/%s/git/trees/%s" % (repo, tree_sha))["tree"]}
        return cache[tree_sha]
    root = gh("GET", "repos/%s/git/commits/%s" % (repo, head))["tree"]["sha"]
    out = {}
    for p in paths:
        t, found = root, None
        parts = p.split("/")
        for i, seg in enumerate(parts):
            e = listing(t).get(seg)
            if e is None:
                break
            if i == len(parts) - 1:
                found = e["sha"] if e["type"] == "blob" else None
            elif e["type"] == "tree":
                t = e["sha"]
            else:
                break
        out[p] = found
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--revert")
    a = ap.parse_args()
    c = Q.cfg()
    repo = c.get("fastdl_repo", "AgitationSkeleton/redchanitfastdl_tf2classic")
    st = Q.load_state(c)
    adds, dels = plan(st, c)
    blobs = []
    for x in adds:
        data = bz2.compress(open(x["src"], "rb").read(), 9)
        blobs.append(dict(x, data=data, sha=git_sha(data)))
    print("plan: %d new file(s) (%d bytes bz2) for %d weapon(s); %d deletion(s) of retired CustomSlop files"
          % (len(blobs), sum(len(b["data"]) for b in blobs), len({b["defindex"] for b in blobs}), len(dels)))
    for b in blobs[:12]:
        print("  ADD", b["path"])
    if a.offline:
        return
    branch = gh("GET", "repos/%s" % repo)["default_branch"]
    head = gh("GET", "repos/%s/git/ref/heads/%s" % (repo, branch))["object"]["sha"]
    if a.revert:
        if head != a.revert:
            raise SystemExit("branch head %s is not %s; refusing to revert over newer commits" % (head, a.revert))
        parent = gh("GET", "repos/%s/git/commits/%s" % (repo, a.revert))["parents"][0]["sha"]
        print("revert %s -> %s" % (head, parent))
        if a.apply:
            gh("PATCH", "repos/%s/git/refs/heads/%s" % (repo, branch), {"sha": parent, "force": True})
            Q.journal(st, "fastdl_revert", from_sha=head, to_sha=parent)
            Q.save_state(st)
        return
    existing = tree_lookup(repo, head, [b["path"] for b in blobs] + [d["path"] for d in dels])
    todo, same, clash = [], [], []
    for b in blobs:
        e = existing.get(b["path"])
        if e is None:
            todo.append(b)
        elif e == b["sha"]:
            same.append(b["path"])
        else:
            clash.append(b["path"])          # someone else's file at our path: never overwrite
    deletions = [d for d in dels if existing.get(d["path"]) == d["sha"]]
    skipped_del = [d["path"] for d in dels if existing.get(d["path"]) != d["sha"]]
    shared = shared_files(repo, head, st, c)
    if shared is None:
        print("WARNING: shared schema/sound files NOT included (config allow_schema_replace is false): clients "
              "would not know the CustomSlop items until the published custom_items_game.txt contains them")
    else:
        for b in shared:
            print("  REPLACE (shared, byte-proof ok) %s  raw %d -> %d bytes, bz2 %d -> %d bytes"
                  % (b["path"], b["old_raw"], b["new_raw"], b["old_bz2"], len(b["data"])))
        todo += shared
    print("remote %s@%s head %s: %d to add, %d already identical, %d CLASH (refused), %d to delete, %d delete skipped"
          % (repo, branch, head[:10], len(todo), len(same), len(clash), len(deletions), len(skipped_del)))
    if clash:
        raise SystemExit("refusing: paths exist with other content: %s" % clash[:10])
    if not a.apply:
        msg = commit_message(len(todo), len(deletions))
        plan_out = dict(repo=repo, branch=branch, parent_head=head, revert_sha=head, add=[dict(path=b["path"], bytes=len(b["data"]),
                        blob_sha=b["sha"]) for b in todo], delete=[d["path"] for d in deletions],
                        total_bz2_bytes=sum(len(b["data"]) for b in todo), commit_message=msg,
                        then=["poll pages/builds/latest until built (POST pages/builds once after %d min)" % STALL_MIN,
                              "HEAD every new URL until 200", "mark weapons published in the catalogue"])
        json.dump(plan_out, open(os.path.join(Q.STATE_DIR, "publish_dryrun.json"), "w"), indent=1)
        print("(dry run - nothing written; plan saved to publish_dryrun.json; revert sha would be %s)" % head)
        return
    entries = []
    for b in todo:
        sha = gh("POST", "repos/%s/git/blobs" % repo, {"content": base64.b64encode(b["data"]).decode(), "encoding": "base64"})["sha"]
        assert sha == b["sha"]
        entries.append({"path": b["path"], "mode": "100644", "type": "blob", "sha": sha})
    entries += [{"path": d["path"], "mode": "100644", "type": "blob", "sha": None} for d in deletions]
    if not entries:
        print("nothing to do")
        return
    tree_sha = gh("GET", "repos/%s/git/commits/%s" % (repo, head))["tree"]["sha"]
    for k in range(0, len(entries), 60):
        tree_sha = gh("POST", "repos/%s/git/trees" % repo, {"base_tree": tree_sha, "tree": entries[k:k + 60]})["sha"]
    msg = commit_message(len(todo), len(deletions))
    commit = gh("POST", "repos/%s/git/commits" % repo, {"message": msg, "tree": tree_sha, "parents": [head]})
    gh("PATCH", "repos/%s/git/refs/heads/%s" % (repo, branch), {"sha": commit["sha"]})
    Q.journal(st, "fastdl_commit", commit=commit["sha"], revert_to=head, added=len(todo), deleted=len(deletions))
    with open(LOG, "a", encoding="utf-8", newline="\n") as f:
        f.write("%s\t%s\t%s\t%d\t%d\n" % (dt.datetime.now().isoformat(timespec="seconds"), head, commit["sha"], len(todo), len(deletions)))
    # ---- Pages build + URL verification
    t0, retriggered = time.time(), False
    while True:
        b = gh("GET", "repos/%s/pages/builds/latest" % repo, check=False) or {}
        if b.get("commit") == commit["sha"] and b.get("status") == "built":
            break
        if b.get("status") == "errored":
            raise SystemExit("Pages build errored - revert with --revert %s --apply" % commit["sha"])
        if time.time() - t0 > STALL_MIN * 60 and not retriggered:
            gh("POST", "repos/%s/pages/builds" % repo, check=False)
            retriggered = True
            Q.journal(st, "pages_retriggered", commit=commit["sha"])
        if time.time() - t0 > 45 * 60:
            raise SystemExit("Pages build did not finish in 45 min (commit %s stays; nothing marked published)" % commit["sha"])
        time.sleep(20)
    import urllib.request
    bad = []
    for b in todo:
        url = c["fastdl_base_url"] + b["path"][len(c["fastdl_prefix"]):]
        for attempt in range(10):
            try:
                req = urllib.request.Request(url, method="HEAD")
                if urllib.request.urlopen(req, timeout=20).status == 200:
                    break
            except Exception:
                pass
            time.sleep(15)
        else:
            bad.append(url)
    if bad:
        Q.journal(st, "fastdl_verify_failed", urls=len(bad))
        Q.save_state(st)
        raise SystemExit("%d URL(s) not 200 yet; weapons stay unpublished" % len(bad))
    for w in st["weapons"].values():
        mine = [b for b in todo if b["defindex"] == w["defindex"]]
        if mine:
            w["published"] = True
            w["published_blobs"] = [dict(path=b["path"], sha=b["sha"]) for b in mine]
        if any(d["defindex"] == w["defindex"] for d in deletions):
            w["unpublished"] = True
    Q.journal(st, "fastdl_verified", commit=commit["sha"])
    Q.save_state(st)
    print("published + verified: commit %s (revert: --revert %s --apply)" % (commit["sha"], commit["sha"]))


if __name__ == "__main__":
    main()
